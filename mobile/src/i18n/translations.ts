export function translateError(language: Language, message: string): string {
  const key = errorKeyByMessage[message]
  if (key) return translate(language, key)
  if (message === 'ShopFlow API request timed out.') {
    return translate(language, 'errors.apiTimeout')
  }
  if (/^(Network request failed|Failed to fetch|Load failed)$/i.test(message)) {
    return translate(language, 'errors.network')
  }
  const unsupportedCurrency = /^This mobile release supports TZS workspaces only; (.+) is not supported offline yet\.$/.exec(message)
  if (unsupportedCurrency) return translate(language, 'errors.currencyUnsupported', { currency: unsupportedCurrency[1] })
  const apiFailure = /^ShopFlow API request failed \((\d+)\)\.$/.exec(message)
  if (apiFailure) return translate(language, 'errors.apiFailure', { status: apiFailure[1] })
  const stockChanged = /^(.+): stock changed\. Review the cart and try again\.$/.exec(message)
  if (stockChanged) return translate(language, 'errors.saleStockChanged', { name: stockChanged[1] })
  const stockShort = /^(.+): only (\d+) in stock\.$/.exec(message)
  if (stockShort) return translate(language, 'pos.stockShort', { name: stockShort[1], count: stockShort[2] })
  return message
}
