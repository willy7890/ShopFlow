export const translationKeys = Object.keys(english) as TranslationKey[]

export function translateRole(language: Language, role: string): string {
  const key = `roles.${role}` as TranslationKey
  return key in english ? translate(language, key) : role.replaceAll('_', ' ')
}

export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  const dictionary = language === 'sw' ? swahili : english
  const template = dictionary[key] ?? english[key]
  if (!template) {
    if (typeof __DEV__ !== 'undefined' && __DEV__) {
      console.error(`[i18n] Missing translation key: ${String(key)}`)
    }
    return `⟦${String(key)}⟧`
  }
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? ''))
}

